--*Thống kê lượt xem theo danh mục*
CREATE OR REPLACE VIEW VIEW_LUOT_XEM_DANH_MUC AS
SELECT DM.MaDM, DM.TenDM, COUNT(DISTINCT LSX.MaLSX) AS LuotXemDanhMuc
FROM DANH_MUC DM
    LEFT JOIN PHIM_DANH_MUC PDM ON DM.MaDM = PDM.MaDM
    LEFT JOIN PHIM P ON P.MaPhim = PDM.MaPhim
    LEFT JOIN VIDEO_PHAT VP ON VP.MaPhim = P.MaPhim
    LEFT JOIN LICH_SU_XEM LSX ON LSX.MaVP = VP.MaVP
GROUP BY DM.MaDM, DM.TenDM;
